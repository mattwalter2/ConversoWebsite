"""Build the vocab seed migration from ../Vocab Words/Spanish_{A1,A2,B1}_Vocab.csv.

The CSVs are frequency lists with defects (see the checks below), so this cleans them:
- one A1 cell holds ~600 space-separated words -> split into tokens
- single letters / abbreviations (d, pp, ii, uu), empty rows -> dropped (need 3+ letters)
- function words and proper names -> dropped (not worth practising)
- duplicates across rows/levels -> first occurrence wins (lowest level, highest frequency)
Usage: python3 scripts/build_vocab_seed.py > supabase/migrations/<ts>_vocab_seed.sql
"""
import csv, re, sys, pathlib

SRC = pathlib.Path(__file__).resolve().parents[2] / "Vocab Words"
WORD = re.compile(r"^[a-záéíóúüñ]{3,}$")
FUNCTION = set("""que los del las por con una sus son les nos ese esa eso esto esta este estos estas esos esas uno unos unas
para pero como más sobre entre cual cuales cuyo cuya cuyos cuyas sino ante tras según hacia desde hasta etc mas aun
ello ésta éste aquel aquella aquellos aquellas mismo misma mismos mismas otro otra otros otras dicho dicha""".split())
NAMES = set("""josé juan carlos maría luis manuel miguel pedro antonio francisco jorge javier fernando rafael alberto pablo
alfonso ramón enrique felipe josep jordi ana carmen isabel teresa elena laura marta madrid barcelona sevilla valencia
rodríguez gonzález garcía fernández lópez martínez sánchez pérez gómez martín jiménez ruiz hernández díaz álvarez muñoz
gutiérrez domínguez vázquez ramírez suárez núñez méndez márquez giménez ibáñez benítez sáez pesetas clinton bush oscar""".split())

seen, rows, dropped = set(), [], {"short/junk": 0, "function": 0, "name": 0, "dup": 0}
for level in ["A1", "A2", "B1"]:
    with open(SRC / f"Spanish_{level}_Vocab.csv", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            for tok in (r["vocab_word"] or "").split():
                w = tok.strip().lower()
                if not WORD.match(w): dropped["short/junk"] += 1; continue
                if w in FUNCTION: dropped["function"] += 1; continue
                if w in NAMES: dropped["name"] += 1; continue
                if w in seen: dropped["dup"] += 1; continue
                seen.add(w)
                rows.append((len(rows) + 1, w, level))

counts = {lvl: sum(1 for _, _, l in rows if l == lvl) for lvl in ["A1", "A2", "B1"]}
print(f"-- Generated by scripts/build_vocab_seed.py from 'Vocab Words/*.csv'. {len(rows)} words: {counts}.")
print(f"-- Dropped: {dropped}.")
print("insert into public.vocab (rank, word, level) values")
print(",\n".join(f"  ({rank}, '{w}', '{lvl}')" for rank, w, lvl in rows) + ";")
print(f"STATS {len(rows)} {counts} {dropped}", file=sys.stderr)
